const assert = require('node:assert/strict')
const path = require('node:path')
const load = require('./dotaznik-ts-loader.cjs')
const root = path.resolve(__dirname, '..')
const { temaObsah } = load(path.join(root, 'src/lib/dotaznik/obsah/index.ts'))
const { splna } = load(path.join(root, 'src/lib/dotaznik/podmienky.ts'))
const { gtext } = load(path.join(root, 'src/lib/dotaznik/obsah/typ.ts'))
const theme = temaObsah('voyeur-exhib', 'voyeur-exhib')
const group = theme.telo.find(b => b.id === 'sex_vedla_paru')
assert.ok(group)
assert.equal(group.podmienka, undefined, 'No dependence on swap or voyeurism experience')
const details = group.bloky.find(b => b.id === 'vedla_paru_podoby')
assert.equal(splna(details.podmienka, {}), false)
assert.equal(splna(details.podmienka, { vedla_paru_chut: { v: 'nie' } }), false)
assert.equal(splna(details.podmienka, { vedla_paru_chut: { v: 'ochota' }, ss_postoj: { v: 'nie' }, fs_postoj: { v: 'nie' } }), true)
const partner = group.bloky.find(b => b.id === 'vedla_paru_partner_tuzi')
assert.ok(partner && !partner.podmienka)
assert.ok(gtext(partner.text, 'm').includes('partnerka'))
assert.ok(gtext(partner.text, 'z').includes('partner'))
assert.ok(gtext(group.uvod, 'm').includes('bez bozkávania, dotykov či sexu'))
assert.ok(gtext(group.uvod, 'z').includes('svojím partnerom'))
const ids = [group.id, ...group.bloky.map(b => b.id), ...details.bloky.map(b => b.id)]
assert.equal(new Set(ids).size, ids.length)
console.log('PASS: same-room without swap, independent interest, both genders, partner desire and detail branching.')
